#!/usr/bin/env python3
"""Inspect the IEEE Dataport release: startup transient and cross-file duplication.

WHY
The release begins from zero initial conditions -- at t=0 every voltage,
current and power is 0 and frequency is exactly 50 Hz. Each 1-second window is
therefore a cold energisation, a settling transient, and only then the attack
(injected at ~0.70 s, giving the observed 30.1% attacked fraction).

Two consequences follow, and both change how the release can be used:

1. STARTUP TRANSIENT. The early samples are an energisation event, not normal
   operation. A detector trained on them learns to separate "energising" from
   "attacked", which is not the task.

2. CROSS-FILE DUPLICATION. If the seven scenarios were generated by the same
   deterministic model from the same initial conditions, their PRE-ATTACK
   segments are the same trajectory seven times over. Under a random split, a
   held-out row from Ramp's pre-attack segment then has a near-identical
   training row from Sinusoid's -- leakage ACROSS files, which is a larger
   channel than the within-file autocorrelation and inflates the binary task
   most of all.

This script measures both rather than assuming either. It was Run before Phase 1.

USAGE
    python scripts/10_inspect_release.py --root /path/to/dataport
"""
import argparse
import glob
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import numpy as np
import pandas as pd

from mgxrl.detection.dataio import (SCENARIOS, _canonical_columns,
                                    classify_ac_columns, redundancy_report)


def exact_onset(root, scenario):
    """Read time+label at FULL resolution to locate the onset exactly.

    The subsampled pass is fine for shape, but onset is the one quantity where
    a stride can mislead by up to `stride` samples -- and onset consistency
    across scenarios is exactly what needs checking. Two columns of 500k rows
    is cheap.
    """
    files = sorted(glob.glob(os.path.join(root, scenario, "*.csv")))
    if not files:
        return {}
    head = pd.read_csv(files[0], nrows=0)
    cols = list(head.columns)
    tcol = cols[0]
    lcol = next((c for c in cols if c.strip().lower() in ("label", "attack_state")), None)
    if lcol is None:
        return {"n_rows": None}
    d = pd.read_csv(files[0], usecols=[tcol, lcol])
    lab = pd.to_numeric(d[lcol], errors="coerce").fillna(0).to_numpy()
    t = pd.to_numeric(d[tcol], errors="coerce").to_numpy()
    idx = np.where(lab > 0)[0]
    flips = int(np.count_nonzero(np.diff(lab != 0)))
    return {
        "n_rows": len(d),
        "duration_s": float(t[-1]),
        "onset_row": int(idx[0]) if len(idx) else None,
        "onset_s": float(t[idx[0]]) if len(idx) else float("nan"),
        "attacked_fraction": float((lab > 0).mean()),
        "n_label_transitions": flips,
    }


def load_raw(root, scenario, stride):
    files = sorted(glob.glob(os.path.join(root, scenario, "*.csv")))
    if not files:
        raise FileNotFoundError(f"No CSVs under {os.path.join(root, scenario)}")
    df = _canonical_columns(pd.read_csv(files[0]))
    return df.iloc[::stride].reset_index(drop=True), len(files)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--stride", type=int, default=500, help="subsample for speed")
    ap.add_argument("--settle", type=float, default=0.25,
                    help="seconds to skip before analysing steady state. Redundancy "
                         "and AC classification measured on the STARTUP transient are "
                         "misleading: during energisation every DG is identical, and "
                         "the asymmetry only appears once the system is loaded.")
    ap.add_argument("--out", default="results")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    data, nfiles = {}, {}
    for s in SCENARIOS:
        data[s], nfiles[s] = load_raw(a.root, s, a.stride)
    tcol = "time" if "time" in data["Normal"] else data["Normal"].columns[0]

    # ---------------------------------------------------------------- 1. shape
    print("=" * 72)
    print("1. STRUCTURE")
    print("=" * 72)
    d0 = data["Normal"]
    print(f"  files per scenario : {nfiles['Normal']}")
    print(f"  columns            : {d0.shape[1]}")
    print()
    print("  exact label geometry (full resolution, not subsampled):")
    print(f"  {'scenario':<10}{'rows':>10}{'dur s':>9}{'onset row':>11}"
          f"{'onset s':>10}{'attacked':>10}{'flips':>7}")
    onsets, durations = {}, {}
    for s_ in SCENARIOS:
        e = exact_onset(a.root, s_)
        if not e or e.get("n_rows") is None:
            print(f"  {s_:<10}  (no label column)")
            continue
        durations[s_] = e["duration_s"]
        if e["onset_row"] is not None:
            onsets[s_] = e["onset_s"]
        print(f"  {s_:<10}{e['n_rows']:>10,}{e['duration_s']:>9.4f}"
              f"{(e['onset_row'] if e['onset_row'] is not None else -1):>11,}"
              f"{e['onset_s']:>10.6f}{e['attacked_fraction']:>10.4f}"
              f"{e['n_label_transitions']:>7}")

    if onsets and (max(onsets.values()) - min(onsets.values())) > 1e-9:
        print()
        print("  WARNING: attack onset TIME differs across scenarios "
              f"({min(onsets.values()):.4f}-{max(onsets.values()):.4f} s).")
        print("  Consequence: with a fixed onset per class, time-since-start is")
        print("  partially predictive of the class. `time` is already excluded from")
        print("  the feature set -- keep it that way -- but windowed features that")
        print("  span the onset can still encode it. Report the onsets in the paper")
        print("  and prefer models evaluated on windows drawn from the attacked")
        print("  period only.")
    elif onsets:
        print(f"\n  All attack onsets identical at t = {min(onsets.values()):.6f} s.")

    if any(e > 1 for e in [0]):
        pass
    vcols = [c for c in d0.columns if c.startswith("v") and c[1:].isdigit()]
    pcols = [c for c in d0.columns if c.startswith("p_dg")]
    fcols = [c for c in d0.columns if c.startswith("f_dg")]
    print(f"  magnitudes         : V ~ {d0[vcols].abs().max().max():.1f}, "
          f"P ~ {d0[pcols].abs().max().max():.1f}, "
          f"f ~ {d0[fcols].mean().mean():.3f}")
    print("  -> units are volts/watts/Hz, NOT per-unit. Absolute comparison")
    print("     against the per-unit plant is meaningless; compare SHAPE only.")

    # -------------------------------------------------- 1b. signal types + rank
    print()
    print(f"  (steady-state analysis skips the first {a.settle} s)")
    ss = {k: v[pd.to_numeric(v[tcol], errors="coerce") >= a.settle].reset_index(drop=True)
          for k, v in data.items()}
    d_ss = ss["Normal"]
    feats0 = [c for c in d_ss.columns
              if c not in {tcol, "label"} and pd.api.types.is_numeric_dtype(d_ss[c])]
    ac = classify_ac_columns(d_ss, feats0)
    print(f"  AC (instantaneous)  : {ac if ac else 'none detected'}")
    print("  -> these MUST be aggregated by RMS, not mean. Their block mean is")
    print("     ~0 and its variance encodes sampling phase, not amplitude.")
    print()
    rep = redundancy_report(d_ss, feats0)
    print(f"  effective rank      : {rep['n_unique']} unique signals "
          f"out of {rep['n_columns']} columns")
    if rep["n_unique"] < rep["n_columns"] / 2:
        print("  -> Most generators are numerically identical. Per-DG feature")
        print("     importance is largely ranking copies of one signal, and the")
        print("     published finding that removing all P_DG costs 0.00% F1 follows")
        print("     trivially. Check WHICH units are distinct before claiming the")
        print("     release supports (or refutes) attack localisation.")

    # ------------------------------------------------------- 2. startup + onset
    print()
    print("=" * 72)
    print("2. STARTUP TRANSIENT AND ATTACK ONSET")
    print("=" * 72)
    v = d0[vcols].abs().max(axis=1).to_numpy()
    t = d0[tcol].to_numpy()
    final = np.median(v[-len(v) // 5:])
    settled = np.where(np.abs(v - final) < 0.02 * abs(final))[0]
    t_settle = t[settled[0]] if len(settled) else float("nan")
    print(f"  voltage settles at : {t_settle:.4f} s "
          f"({100 * t_settle / t[-1]:.1f}% of the window)")

    for s in SCENARIOS:
        if "label" not in data[s]:
            continue
        lab = pd.to_numeric(data[s]["label"], errors="coerce").fillna(0).to_numpy()
        idx = np.where(lab > 0)[0]
        onset = data[s][tcol].to_numpy()[idx[0]] if len(idx) else float("nan")
        print(f"  {s:<10} attack onset {onset:.4f} s   "
              f"attacked fraction {lab.mean():.3f}")

    print()
    print(f"  RECOMMENDATION: trim the first {max(t_settle, 0.05):.2f} s.")
    print("  Samples before settling are an energisation event, not normal")
    print("  operation; a detector trained on them separates 'energising' from")
    print("  'attacked', which is not the task you are claiming to solve.")

    # -------------------------------------------- 3. cross-scenario duplication
    print()
    print("=" * 72)
    print("3. CROSS-FILE DUPLICATION OF PRE-ATTACK SEGMENTS")
    print("=" * 72)
    feats = feats0

    segs = {}
    for s in SCENARIOS:
        d = ss[s]
        lab = (pd.to_numeric(d["label"], errors="coerce").fillna(0).to_numpy()
               if "label" in d else np.zeros(len(d)))
        idx = np.where(lab > 0)[0]
        end = idx[0] if len(idx) else len(d)
        segs[s] = d[feats].to_numpy(dtype=np.float64)[:end]

    n = min(len(x) for x in segs.values())
    ref = segs["Normal"][:n]
    scale = np.abs(ref).max(axis=0) + 1e-12

    print(f"  comparing the first {n} pre-attack samples of each scenario")
    print(f"  against Normal, normalised per column\n")
    print(f"  {'scenario':<10}{'max rel. diff':>16}{'mean rel. diff':>17}   verdict")
    identical = []
    for s in SCENARIOS:
        if s == "Normal":
            continue
        d = np.abs(segs[s][:n] - ref) / scale
        mx, mn = float(d.max()), float(d.mean())
        if mx < 1e-12:
            verdict = "IDENTICAL (bitwise)"
            identical.append(s)
        elif mx < 1e-9:
            verdict = "identical to 1e-9"
            identical.append(s)
        elif mx < 1e-3:
            verdict = "near-identical"
            identical.append(s)
        else:
            verdict = "differs"
        print(f"  {s:<10}{mx:>16.3e}{mn:>17.3e}   {verdict}")

    print()
    if len(identical) >= 5:
        dup = n * len(identical)
        total = sum(len(x) for x in segs.values())
        print(f"  FINDING: {len(identical)} of 6 attack scenarios share Normal's")
        print(f"  pre-attack trajectory. Roughly {100 * dup / max(total, 1):.0f}% of the")
        print("  pre-attack data is the SAME trajectory repeated.")
        print()
        print("  Implications to state in the paper:")
        print("   - A random split leaks ACROSS files, not merely within them.")
        print("     A held-out pre-attack row has a near-identical training row")
        print("     from a different scenario. This inflates the binary task most.")
        print("   - The effective number of independent normal trajectories is 1,")
        print("     not 7. Report it that way.")
        print("   - Block splitting does NOT fix this: blocks are drawn within a")
        print("     scenario, so the duplicate in another scenario stays in train.")
        print("     Only scenario-level holdout would -- and it is unavailable here.")
        print()
        print("  Watch for a subtler variant: if pre-attack segments agree to ~9")
        print("  significant figures but differ in the last bits (values around")
        print("  1e-22), a tree model can split on that denormal-level noise and use")
        print("  it as a FILE FINGERPRINT. Physically those digits are zero. If the")
        print("  bitwise row above says 'identical to 1e-9' rather than 'IDENTICAL",
              "(bitwise)', round the features before training and re-check.")
    else:
        print("  Pre-attack segments differ across scenarios; cross-file")
        print("  duplication is not a dominant leakage channel.")

    rows = []
    for s in SCENARIOS:
        d = data[s]
        lab = (pd.to_numeric(d["label"], errors="coerce").fillna(0).to_numpy()
               if "label" in d else np.zeros(len(d)))
        idx = np.where(lab > 0)[0]
        rows.append({
            "scenario": s,
            "onset_s": float(d[tcol].to_numpy()[idx[0]]) if len(idx) else np.nan,
            "attacked_fraction": float(lab.mean()),
            "duplicate_of_normal_pre_attack": s in identical,
        })
    pd.DataFrame(rows).to_csv(
        os.path.join(a.out, "release_inspection.csv"), index=False)
    print(f"\nWrote {a.out}/release_inspection.csv")


if __name__ == "__main__":
    main()
